"""Generate figures/fig2.tex: three result views that the tables do not show.

(a) safe success per task family, (b) CDF of the closest approach of the real
arm to any obstacle per rollout, (c) CDF of steps to completion on the scenes
that every compared method completes safely. All numbers come from the
artifact's main run (outputs/calvin_final/*.jsonl, 1000 test scenes).

    python3 figures/make_fig2.py [ARTIFACT_ROOT]

ARTIFACT_ROOT defaults to this repository. Also writes
figures/fig2_numbers.txt with the values quoted in the text.
"""
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
DEFAULT_ROOT = HERE.parents[3]
ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_ROOT
FINAL = ROOT / "outputs" / "calvin_final"
SCENES = ROOT / "shortstop" / "calvin" / "data" / "scenes" / "final_scenes.json"

METHODS = [("Unshielded", "unshielded", "black!55", "densely dotted"),
           ("STL-Monitor", "stl_monitor_hold", "violet!70!black", "dashed"),
           ("MPC-Filter", "mpc_filter_hold", "blue!70!black", "dashdotted"),
           ("CBF", "cbf_hold", "orange!85!black", "solid"),
           ("ShortStop", "shortstop_hold", "red!80!black", "solid")]
FAMILIES = [("push", "Push"), ("rotate", "Rotate"), ("lift", "Lift"), ("drawer", "Drawer"), ("switch", "Switch")]


def family(task):
    if task.startswith(("push_red", "push_blue", "push_pink")):
        return "push"
    if task.startswith("rotate"):
        return "rotate"
    if task.startswith("lift"):
        return "lift"
    if "drawer" in task or "slide" in task:
        return "drawer"
    return "switch"


def safe(e):
    return e["reached"] and not e["violated"]


def cdf_points(values, grid):
    v = np.sort(np.asarray(values, dtype=float))
    return [(x, 100.0 * np.searchsorted(v, x, side="right") / len(v)) for x in grid]


def coords(pts):
    return " ".join(f"({x:.2f},{y:.2f})" for x, y in pts)


def main():
    runs = {lab: {e["scene_id"]: e for e in map(json.loads, open(FINAL / f"{name}.jsonl"))}
            for lab, name, _, _ in METHODS}
    scenes = {s["scene_id"]: s for s in json.load(open(SCENES))["scenes"]}
    keys = sorted(runs["ShortStop"])
    assert all(set(r) == set(keys) for r in runs.values())
    fam = {k: family(scenes[k]["task_name"]) for k in keys}
    numbers = []

    # (a) safe success per task family
    bar_methods = ["Unshielded", "STL-Monitor", "CBF", "ShortStop"]
    rate = {m: {f: 100 * np.mean([safe(runs[m][k]) for k in keys if fam[k] == f]) for f, _ in FAMILIES}
            for m, _, _, _ in METHODS}
    count = {f: sum(fam[k] == f for k in keys) for f, _ in FAMILIES}
    numbers.append("family sizes " + str(count))
    for m in rate:
        numbers.append(f"(a) {m}: " + ", ".join(f"{f} {rate[m][f]:.1f}" for f, _ in FAMILIES))

    # (b) closest approach per rollout, mm
    grid_b = np.linspace(-10, 50, 121)
    clear = {m: [1000 * runs[m][k]["min_clearance"] for k in keys] for m, _, _, _ in METHODS}
    for m in clear:
        c = np.array(clear[m])
        numbers.append(f"(b) {m}: p5 {np.percentile(c, 5):.1f} median {np.median(c):.1f} mm, "
                       f"share below 10 mm {100*np.mean(c < 10):.1f}%")

    # (c) steps to completion on scenes all four main methods complete safely
    four = ["Unshielded", "MPC-Filter", "CBF", "ShortStop"]
    common = [k for k in keys if all(safe(runs[m][k]) for m in four)]
    steps = {m: [runs[m][k]["steps_taken"] for k in common] for m in four}
    grid_c = np.arange(20, 181, 2)
    for m in four:
        s = np.array(steps[m])
        numbers.append(f"(c) {m}: n {len(s)} median {np.median(s):.0f} p90 {np.percentile(s, 90):.0f} mean {s.mean():.1f}")
    d = np.array(steps["ShortStop"]) - np.array(steps["Unshielded"])
    numbers.append(f"(c) ShortStop minus Unshielded steps: median {np.median(d):.0f}, slower {np.sum(d > 0)}, "
                   f"equal {np.sum(d == 0)}, faster {np.sum(d < 0)}")

    bins = np.arange(-42, 43, 4)
    hist, _ = np.histogram(np.clip(d, -41.9, 41.9), bins=bins)   # outliers go to the end bins
    numbers.append(f"(c) beyond +-40 steps: {int(np.sum(np.abs(d) > 40))} scenes")
    numbers.append(f"(c) |difference| <= 10 steps: {100*np.mean(np.abs(d) <= 10):.1f}% of scenes")

    style = {m: (c, ls) for m, _, c, ls in METHODS}
    W = "3.95cm"
    t = ["% Generated by figures/make_fig2.py. Do not edit by hand.\n",
         "\\begin{tikzpicture}\n",
         "\\pgfplotsset{every axis/.append style={scale only axis, width=2.85cm, height=2.35cm, tick label style={font=\\tiny},\n"
         "  label style={font=\\scriptsize}, title style={font=\\scriptsize\\bfseries, yshift=-1.2ex},\n"
         "  grid=major, grid style={gray!20}, ylabel shift=-4pt, xlabel shift=-2pt}}\n"]
    # (a)
    t.append("\\begin{axis}[name=a, ybar=0pt, bar width=2.2pt, ymin=0, ymax=100, ylabel={Safe success (\\%)},\n"
             "  symbolic x coords={" + ",".join(f for f, _ in FAMILIES) + "}, xtick=data,\n"
             "  xticklabels={" + ",".join(lab for _, lab in FAMILIES) + "},\n"
             "  xticklabel style={font=\\tiny, rotate=35, anchor=north east, inner sep=1pt}, enlarge x limits=0.12,\n"
             "  title={(a) By task family}]\n")
    for m in bar_methods:
        c, _ = style[m]
        t.append(f"\\addplot[fill={c}, draw=none] coordinates {{" +
                 " ".join(f"({f},{rate[m][f]:.1f})" for f, _ in FAMILIES) + "};\n")
    t.append("\\end{axis}\n")
    # (b)
    t.append("\\begin{axis}[name=b, at={(a.south east)}, anchor=south west, xshift=1.12cm, xmin=-10, xmax=50, ymin=0, ymax=100,\n"
             "  xlabel={Closest approach (mm)}, ylabel={Rollouts (\\%)},\n"
             "  title={(b) Closest approach}]\n")
    t.append("\\fill[red!10] (axis cs:-10,0) rectangle (axis cs:0,100);\n")
    for m, _, c, ls in METHODS:
        t.append(f"\\addplot[{c}, {ls}, line width=0.8pt, const plot, mark=none] coordinates {{{coords(cdf_points(clear[m], grid_b))}}};\n")
    t.append("\\end{axis}\n")
    # (c)
    t.append("\\begin{axis}[name=c, at={(b.south east)}, anchor=south west, xshift=1.12cm, ybar, bar width=4, ymin=0,\n"
             "  xmin=-42, xmax=42, xtick={-40,-20,0,20,40},\n"
             "  xlabel={Extra steps vs.\\ unshielded}, ylabel={Scenes},\n"
             "  title={(c) Time cost}]\n")
    c, _ = style["ShortStop"]
    t.append(f"\\addplot[fill={c}!70, draw={c}, line width=0.3pt] coordinates {{" +
             " ".join(f"({b+2},{h})" for b, h in zip(bins[:-1], hist)) + "};\n")
    t.append("\\draw[black!60, dashed] (axis cs:0,\\pgfkeysvalueof{/pgfplots/ymin}) -- (axis cs:0,\\pgfkeysvalueof{/pgfplots/ymax});\n")
    t.append("\\end{axis}\n")
    # shared legend above the three panels
    t.append("\\matrix[matrix of nodes, anchor=south, font=\\scriptsize, column sep=7pt, inner sep=1pt,\n"
             "  nodes={anchor=west}] at ($(b.outer north)+(0,0.05)$) {\n")
    cells = []
    for m, _, c, ls in METHODS:
        cells.append(f"\\tikz\\draw[{c}, {ls}, line width=1.4pt] (0,0) -- (0.45,0); {m.replace('ShortStop', chr(92) + 'sys{}')}")
    t.append(" & ".join(cells) + " \\\\\n};\n")
    t.append("\\end{tikzpicture}\n")
    (HERE / "fig2.tex").write_text("".join(t))
    (HERE / "fig2_numbers.txt").write_text("\n".join(numbers) + "\n")
    print("\n".join(numbers))


if __name__ == "__main__":
    main()
