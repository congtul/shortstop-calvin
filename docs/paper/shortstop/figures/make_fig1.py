"""Generate figures/fig1.tex: a walk-through of one ShortStop decision.

Top-down sketch of an illustrative CALVIN scene: the gripper reaches for a
drawer handle past a ball the policy cannot see. The band radii are the
paper's calibrated radii (9.6, 14.7, 18.5, 22.4 mm) and the margin is the
paper's 3 mm. Scene geometry and gaps are illustrative and drawn to scale
(1 drawing unit = 1 / MM mm).

    python3 figures/make_fig1.py   # writes figures/fig1.tex
"""
from pathlib import Path

import numpy as np

OUT = Path(__file__).with_name("fig1.tex")
MM = 0.0135                      # drawing units per millimetre
RADII_MM = [9.6, 14.7, 18.5, 22.4]
MARGIN_MM = 3.0
START = np.array([0.30, 0.40])
CTRL = np.array([0.60, 2.10])
GOAL = np.array([2.55, 2.25])
BALL = np.array([1.25, 1.90])
BALL_R = 0.40                    # about 30 mm
N_STEPS = 10                     # rows in one chunk (MDT emits L = 10)
H = 4                            # checked and executed rows
PW, PH, GAP = 2.85, 2.55, 0.15   # panel width, height, gap


def bez(t):
    return (1 - t) ** 2 * START + 2 * (1 - t) * t * CTRL + t ** 2 * GOAL


def plan(offset=0.0):
    pts = np.array([bez(t) for t in np.linspace(0, 1, N_STEPS + 1)])
    return pts + offset * np.array([0.6, -0.8])


def clearance_mm(pts):
    """Gap between each checked step's band and the ball, in mm."""
    return [(np.linalg.norm(pts[k] - BALL) - BALL_R - RADII_MM[k - 1] * MM) / MM for k in range(1, H + 1)]


def repair(pts, rounds=5):
    """Repeat Eq. (5) for up to `rounds` rounds (c = 5 in the paper): move the
    rows up to the worst step away from the ball, then re-check."""
    new = pts.copy()
    first_worst = None
    for _ in range(rounds):
        cl = clearance_mm(new)
        if min(cl) >= MARGIN_MM:
            break
        k_star = int(np.argmin(cl)) + 1
        first_worst = first_worst or k_star
        d = (new[k_star] - BALL) / np.linalg.norm(new[k_star] - BALL)
        need = (MARGIN_MM + 1.0 - cl[k_star - 1]) * MM     # gamma + mu, mu = 1 mm
        for k in range(1, N_STEPS + 1):
            # rows up to k* are edited; relative rows shift later positions in parallel
            w = min(k / k_star, 1.0)
            new[k] = new[k] + w * need * d
    return new, first_worst


def p(x):
    return f"({x[0]:.3f},{x[1]:.3f})"


def smooth(pts, style):
    return f"\\draw[{style}] plot[smooth, tension=0.6] coordinates {{{' '.join(p(q) for q in pts)}}};\n"


def panel(i, title, body, caption, ball_note=False):
    dx = i * (PW + GAP)
    s = f"\\begin{{scope}}[xshift={dx:.2f}cm]\n"
    s += f"\\draw[frame] (0,0) rectangle ({PW},{PH});\n"
    s += f"\\node[ttl, anchor=base west] at (0.02,{PH + 0.10}) {{{title}}};\n"
    s += f"\\fill[brown!55] ({GOAL[0]-0.05:.3f},{GOAL[1]-0.16:.3f}) rectangle ({GOAL[0]+0.05:.3f},{GOAL[1]+0.16:.3f});\n"
    s += f"\\node[lbl, anchor=north] at ({GOAL[0]:.3f},{GOAL[1]-0.18:.3f}) {{handle}};\n"
    s += f"\\fill[ballc] {p(BALL)} circle ({BALL_R});\n"
    if ball_note:
        s += f"\\node[lbl, align=left, text=red!60!black, anchor=west] at ({BALL[0]-0.30:.3f},{BALL[1]-0.62:.3f}) {{ball the policy\\\\cannot see}};\n"
    s += body
    s += f"\\node[grip] at {p(START)} {{}};\n"
    s += f"\\node[lbl, anchor=west] at ({START[0]+0.10:.3f},{START[1]-0.05:.3f}) {{gripper}};\n"
    s += f"\\node[capt] at ({PW/2:.3f},-0.06) {{{caption}}};\n"
    s += "\\end{scope}\n"
    return s


def build():
    base = plan()
    cl0 = clearance_mm(base)
    fixed, k_star = repair(base)
    cl1 = clearance_mm(fixed)
    print("clearance before (mm):", [round(c, 1) for c in cl0])
    print("clearance after  (mm):", [round(c, 1) for c in cl1], "worst step", k_star)
    assert min(cl0) < MARGIN_MM <= min(cl1)

    t = ["% Generated by figures/make_fig1.py. Do not edit by hand.\n",
         "\\begin{tikzpicture}[x=1cm,y=1cm,\n"
         "  frame/.style={draw=black!25, rounded corners=2pt},\n"
         "  ttl/.style={font=\\footnotesize\\bfseries, inner sep=1pt},\n"
         "  lbl/.style={font=\\tiny, inner sep=1pt},\n"
         f"  capt/.style={{font={{\\scriptsize\\hyphenpenalty10000\\exhyphenpenalty10000\\relax}}, text width={PW}cm, align=left, anchor=north, inner sep=0pt}},\n"
         "  grip/.style={draw=black, fill=black!70, minimum size=5pt, inner sep=0pt, rectangle},\n"
         "  ballc/.style={red!30},\n"
         "  badband/.style={fill=red!12, draw=red!70!black, line width=0.4pt},\n"
         "  band/.style={fill=blue!10, draw=blue!50, line width=0.4pt},\n"
         "  okband/.style={fill=green!14, draw=green!45!black, line width=0.4pt},\n"
         "  planline/.style={black!75, line width=0.6pt},\n"
         "  stepdot/.style={circle, fill=black, inner sep=0.75pt}]\n"]

    # 1. Propose
    body = "".join(smooth(plan(off), "black!50, line width=0.45pt") for off in (-0.045, -0.015, 0.015, 0.045))
    t.append(panel(0, "1. Propose", body,
                   "The policy proposes four nearly identical 10-step plans. All run into the ball.",
                   ball_note=True))

    # 2. Check
    body = ""
    for k in range(H, 0, -1):
        body += f"\\draw[{'badband' if cl0[k-1] < MARGIN_MM else 'band'}] {p(base[k])} circle ({RADII_MM[k-1]*MM:.3f});\n"
    body += smooth(base, "planline")
    for k in range(1, H + 1):
        r = RADII_MM[k - 1] * MM
        body += f"\\node[stepdot] at {p(base[k])} {{}};\n"
        body += f"\\node[lbl, anchor=east] at ({base[k][0]-r-0.01:.3f},{base[k][1]:.3f}) {{{k}}};\n"
    ks = int(np.argmin(cl0)) + 1
    u = (base[ks] - BALL) / np.linalg.norm(base[ks] - BALL)
    wp = BALL + u * BALL_R
    body += f"\\node[star, star points=5, star point ratio=2.2, fill=red!80!black, inner sep=1.1pt] at {p(wp)} {{}};\n"
    body += (f"\\draw[red!70!black, line width=0.3pt] {p(wp)} -- (1.45,1.10) node[lbl, anchor=north west, align=left, text=red!70!black] "
             f"{{worst point:\\\\step {ks} band\\\\hits the ball}};\n")
    t.append(panel(1, "2. Check", body,
                   "Steps 1 to 4 get safety bands of 10 to 22\\,mm. One band hits the ball: rejected."))

    # 3. Repair
    body = smooth(base, "black!35, dashed, line width=0.5pt")
    for k in range(H, 0, -1):
        body += f"\\draw[okband] {p(fixed[k])} circle ({RADII_MM[k-1]*MM:.3f});\n"
    body += smooth(fixed, "planline")
    for k in range(1, H + 1):
        body += f"\\node[stepdot] at {p(fixed[k])} {{}};\n"
    body += f"\\draw[-{{Latex[length=1.5mm]}}, red!70!black, line width=0.7pt] {p(base[k_star])} -- {p(fixed[k_star])};\n"
    body += (f"\\node[lbl, anchor=north west, align=left, text=green!30!black] at (1.10,1.12) "
             f"{{gap {min(cl1):.0f}\\,mm $\\geq$\\\\3\\,mm margin:\\\\certified}};\n")
    t.append(panel(2, "3. Repair", body,
                   "The worst point shows which way to push. Steps up to it are edited, then rechecked."))

    # 4. Run and repeat
    body = smooth(base, "black!20, dashed, line width=0.4pt")
    body += smooth(fixed[:H + 1], "green!40!black, line width=1.5pt")
    body += smooth(fixed[H:], "black!35, dashed, line width=0.5pt")
    body += f"\\node[grip, fill=green!40!black] at {p(fixed[H])} {{}};\n"
    body += f"\\node[lbl, anchor=north west, align=left] at ({fixed[H][0]+0.08:.3f},{fixed[H][1]-0.06:.3f}) {{ask the\\\\policy again}};\n"
    t.append(panel(3, "4. Run, repeat", body,
                   "The robot runs the 4 checked steps, then asks again. With no safe plan it holds still."))

    # Delay strip
    y, x0, w = -2.0, 0.0, 0.55
    groups = [("orange!25", "orange!70!black", "sent before,\\\\runs now"),
              ("green!25", "green!45!black", "new,\\\\runs now"),
              ("green!8", "green!45!black", "new,\\\\runs later")]
    for g, (fill, draw, lab) in enumerate(groups):
        for i in (2 * g, 2 * g + 1):
            t.append(f"\\draw[fill={fill}, draw={draw}] ({x0+w*i:.2f},{y-0.15}) rectangle ({x0+w*(i+1):.2f},{y+0.15});\n")
        t.append(f"\\node[lbl, anchor=north, align=center] at ({x0+w*(2*g+1):.2f},{y-0.18}) {{{lab}}};\n")
    t.append(f"\\draw[decorate, decoration={{brace, amplitude=3pt}}, line width=0.5pt] ({x0:.2f},{y+0.19}) -- ({x0+6*w:.2f},{y+0.19}) "
             f"node[midway, above=2pt, lbl] {{checked together}};\n")
    t.append(f"\\node[font=\\scriptsize, anchor=west, text width=8.2cm, align=left] at ({x0+6*w+0.25:.2f},{y-0.05}) "
             f"{{\\textbf{{With inference delay.}} The next plan is computed while earlier steps still run. Each decision "
             f"runs 2 steps sent earlier and 2 new ones, and sends 2 more that run during the next computation. None of "
             f"them can be changed later, and the check must therefore cover all six.}};\n")
    t.append("\\end{tikzpicture}\n")
    OUT.write_text("".join(t))
    print("wrote", OUT)


if __name__ == "__main__":
    build()
